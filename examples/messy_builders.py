"""Deterministic builders for the five messy sample survey CSVs.

Each builder returns ``(header, rows)`` and is driven by a seeded
:class:`random.Random`, so the committed ``examples/*.csv`` fixtures can be
regenerated byte-for-byte.
"""

from __future__ import annotations

import random
from datetime import datetime, timedelta

SEED = 20240928
MISSING = ["", "N/A", "n/a", "null", "-", "?", "NaN", " "]
DATE_FORMATS = ["%Y-%m-%d", "%d/%m/%Y", "%m/%d/%Y", "%d-%b-%Y", "%b %d, %Y"]

DEPARTMENTS = ["Engineering", "Sales", "Marketing", "Support", "Finance"]
ROLES = ["Individual Contributor", "Team Lead", "Manager", "Director"]
PLANS = ["Free", "Pro", "Team", "Enterprise"]
CITIES = ["Berlin", "Lisbon", "Austin", "Toronto", "Lisbon", "Bangalore"]
SEGMENTS = ["SMB", "Mid-Market", "Enterprise", "Startup"]
INTENTS = ["Very likely", "Likely", "Neutral", "Unlikely", "Very unlikely"]
NAMES = ["Amara Okafor", "Noah Berg", "Mia Silva", "Tomas Novak", "Priya Raman"]
RECOMMEND = ["Yes", "No", "Maybe"]
ATTEND = ["Yes", "No", "Definitely", "Probably not"]
RISK = ["low", "medium", "high"]
SEX = ["Female", "Male", "Non-binary"]
SMOKER = ["Y", "N", "yes", "no", "1", "0", "Former"]
DECIDER = ["yes", "no", "unknown", "Yes - VP"]
DISCOUNTS = ["0", "10", "15%", "20 %", "0.0", "25"]
SPENDS = [0, 0, 149, 299, 1400, 12_500]
TICKETS = [0, 0, 1, 1, 2, 3, 8]
BASE_PRICE = {"Startup": 29, "SMB": 79, "Mid-Market": 149, "Enterprise": 249}
BP = [999, 88, 240]


def clamp(value: int, low: int, high: int) -> int:
    """Keep a derived value inside its valid range."""
    return max(low, min(high, value))


def missing(rng: random.Random, value: str, p: float = 0.08) -> str:
    """Return a blank/sentinel value with probability ``p``, else ``value``."""
    return rng.choice(MISSING) if rng.random() < p else value


def messy_case(rng: random.Random, value: str) -> str:
    """Randomly pad or re-case a categorical value."""
    roll = rng.random()
    if roll < 0.10:
        return f" {value}"
    if roll < 0.18:
        return f"{value} "
    if roll < 0.30:
        return value.lower()
    if roll < 0.38:
        return value.upper()
    return value


def messy_date(rng: random.Random, start: datetime) -> str:
    """Render a date using one of several plausible real-world formats."""
    return (start + timedelta(days=rng.randint(0, 120))).strftime(rng.choice(DATE_FORMATS))


def comments(rng: random.Random, pool: list[str], p: float = 0.45) -> str:
    """Return a free-text response, usually blank."""
    return rng.choice(pool) if rng.random() < p else ""


def with_duplicates(rng: random.Random, rows: list[list[str]], count: int) -> list[list[str]]:
    """Return the rows plus ``count`` exact copies of random rows."""
    return rows + [list(rows[i]) for i in rng.sample(range(len(rows)), count)]


def employees(rng: random.Random) -> tuple[list[str], list[list[str]]]:
    """Build an HR engagement export with labelled Likert scores."""
    header = [
        "Employee ID", "Department ", "tenure_yrs", "Role", "Engagement Score",
        "manager_support", "Would Recommend", "survey_date", "Comments",
    ]
    agree = ["Strongly disagree", "Disagree", "Neutral", "Agree", "Strongly agree"]
    pool = [
        "Great team, poor tooling.", "Workload is too high right now.",
        "Needs better career pathing.", "Manager is supportive and clear.",
        "Love the mission, pay is below market.",
    ]
    rows: list[list[str]] = []
    for i in range(180):
        # Engagement tracks manager support, so the correlation analysis has
        # something real to find.
        support = rng.randint(1, 5)
        score = clamp(support + rng.choice([-1, 0, 0, 1]), 1, 5)
        shown = f"{score} - {agree[score - 1]}" if rng.random() < 0.18 else str(score)
        rows.append([
            f"E{1000 + i}", messy_case(rng, rng.choice(DEPARTMENTS)),
            missing(rng, str(rng.randint(0, 12)), 0.06), messy_case(rng, rng.choice(ROLES)),
            missing(rng, shown, 0.09), missing(rng, str(support), 0.12),
            messy_case(rng, rng.choice(RECOMMEND)), messy_date(rng, datetime(2024, 3, 1)),
            comments(rng, pool),
        ])
    rows = with_duplicates(rng, rows, 6)
    rows.append(list(rows[3]))
    return header, rows


def customers(rng: random.Random) -> tuple[list[str], list[list[str]]]:
    """Build a customer NPS export with currency-formatted spend."""
    header = [
        "response_id", "Customer Name", "Plan", "nps_score", "satisfaction_(1-5)",
        "support_tickets", "Annual Spend", "churn_risk", "response_date", "feedback",
    ]
    names = ["Ada Lovelace", "Grace Hopper", "Alan Turing", "Katherine Johnson", "Ken Thompson"]
    pool = [
        "Onboarding took too long.", "Pricing feels high for what we use.",
        "Best tool in its class.", "Support replies fast and fixes things.",
        "Migration from a competitor was smooth.",
    ]
    rows: list[list[str]] = []
    for i in range(200):
        # Satisfaction falls with ticket volume, and NPS follows satisfaction.
        tickets = rng.choice(TICKETS)
        satisfaction = clamp(5 - tickets // 2 + rng.choice([-1, 0, 0, 1]), 1, 5)
        nps = clamp(satisfaction * 2 + rng.choice([-2, -1, 0, 1, 2]), 0, 10)
        style = rng.random()
        shown = f"{nps}/10" if style < 0.12 else (f"{nps} out of 10" if style < 0.2 else str(nps))
        spend = rng.choice(SPENDS)
        rows.append([
            f"R{i + 1:04d}", missing(rng, rng.choice(names), 0.05),
            messy_case(rng, rng.choice(PLANS)), missing(rng, shown, 0.10),
            missing(rng, str(satisfaction), 0.07),
            missing(rng, str(tickets), 0.15),
            missing(rng, rng.choice([f"${spend}", f"${spend:,}.00", str(spend)]), 0.11),
            messy_case(rng, rng.choice(RISK)), messy_date(rng, datetime(2024, 1, 5)),
            comments(rng, pool, 0.35),
        ])
    return header, with_duplicates(rng, rows, 8)


def events(rng: random.Random) -> tuple[list[str], list[list[str]]]:
    """Build an event feedback export with a BOM, a blank row and minutes."""
    header = [
        "Reg ID", "attendee_name", "Session Rating", "speaker_rating",
        "Would attend again?", "session_length_mins", "Feedback Date", "City", "notes",
    ]
    pool = [
        "Audio was hard to hear.", "Loved the workshop track.", "Room was too cold.",
        "Great networking.", "Slides never shared.",
    ]
    rows: list[list[str]] = []
    for i in range(160):
        # One overall experience drives both session and speaker scores.
        base = rng.randint(1, 5)
        session = clamp(base + rng.choice([-1, 0, 0, 1]), 1, 5)
        speaker = clamp(base + rng.choice([-1, 0, 0, 1]), 1, 5)
        minutes = rng.choice([30, 45, 60, 90])
        shown = rng.choice([str(minutes), f"{minutes} min", f"{minutes} mins", f"{minutes} MIN"])
        rows.append([
            f"REG-{2000 + i}", missing(rng, rng.choice(NAMES), 0.06),
            missing(rng, str(session), 0.08), missing(rng, str(speaker), 0.14),
            messy_case(rng, rng.choice(ATTEND)), missing(rng, shown, 0.09),
            messy_date(rng, datetime(2024, 5, 10)), messy_case(rng, rng.choice(CITIES)),
            comments(rng, pool, 0.30),
        ])
    rows = with_duplicates(rng, rows, 5)
    rows.append([""] * len(header))
    return header, rows


def pricing(rng: random.Random) -> tuple[list[str], list[list[str]]]:
    """Build a pricing survey with WTP in several currency spellings."""
    header = [
        "respondent_id", "Segment", "willingness_to_pay", "purchase_intent",
        "price_shown", "discount_pct", "interview_date", "decision_maker", "verbatim",
    ]
    pool = [
        "Price is fair if it replaces two tools.", "We would need SSO before buying.",
        "Budget is locked until next quarter.", "Too expensive for our team size.",
    ]
    rows: list[list[str]] = []
    for i in range(170):
        # Bigger segments pay more, and the shown price anchors willingness to pay.
        segment = rng.choice(SEGMENTS)
        wtp = max(19, BASE_PRICE[segment] + rng.choice([-20, -10, 0, 0, 10, 39]))
        shown = rng.choice([str(wtp), f"${wtp}", f"${wtp}.00", f"${wtp:,}", f"USD {wtp}"])
        asked = max(19, wtp + rng.choice([-40, -25, -10, 0, 15, 30]))
        discount = rng.choice(DISCOUNTS)
        if wtp < 100 and rng.random() < 0.5:
            discount = rng.choice(["15%", "20 %", "25"])
        rows.append([
            f"P{i + 1:03d}", messy_case(rng, segment), missing(rng, shown, 0.12),
            messy_case(rng, rng.choice(INTENTS)),
            missing(rng, rng.choice([str(asked), f"${asked}", f"${asked}.99"]), 0.05),
            missing(rng, discount, 0.18), messy_date(rng, datetime(2024, 2, 1)),
            messy_case(rng, rng.choice(DECIDER)), comments(rng, pool, 0.33),
        ])
    return header, with_duplicates(rng, rows, 7)


def health(rng: random.Random) -> tuple[list[str], list[list[str]]]:
    """Build a clinic checkup export with comma decimals and BP outliers."""
    header = [
        "patient_id", "visit_date", "age", "sex", "bmi", "systolic_bp",
        "smoker", "exercise_days_per_week", "notes",
    ]
    pool = [
        "Referred to nutrition clinic.", "BP re-check in 3 months.",
        "Reports better sleep.", "History of asthma.", "No follow-up needed.",
    ]
    rows: list[list[str]] = []
    for i in range(190):
        # Blood pressure rises with age and BMI; exercise falls as BMI rises.
        age = rng.randint(19, 84)
        bmi = round(rng.gauss(26.5, 4.2), 1)
        bmi_text = f"{bmi:.1f}".replace(".", ",") if rng.random() < 0.08 else f"{bmi:.1f}"
        measured = round(92 + 0.35 * age + 0.7 * bmi + rng.gauss(0, 6))
        bp = measured if rng.random() > 0.01 else rng.choice(BP)
        exercise = clamp(7 - int(bmi / 6) + rng.choice([-1, 0, 0, 1]), 0, 7)
        rows.append([
            f"H{i + 1:04d}", messy_date(rng, datetime(2024, 6, 1)),
            missing(rng, f"{age} years" if rng.random() < 0.07 else str(age), 0.04),
            messy_case(rng, rng.choice(SEX)), missing(rng, bmi_text, 0.06),
            missing(rng, str(bp), 0.05), messy_case(rng, rng.choice(SMOKER)),
            missing(rng, str(exercise), 0.12), comments(rng, pool, 0.25),
        ])
    return header, with_duplicates(rng, rows, 4)
